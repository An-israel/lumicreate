import { useState, useEffect } from "react";
import { useNavigate } from "react-router-dom";
import { useAuth } from "@/hooks/useAuth";
import { useCart } from "@/hooks/useCart";
import { supabase } from "@/integrations/supabase/client";
import { initializePayment } from "@/lib/paystack";
import Layout from "@/components/layout/Layout";
import CoinBenefitsBanner from "@/components/shop/CoinBenefitsBanner";
import { Card, CardContent, CardDescription, CardHeader, CardTitle } from "@/components/ui/card";
import { Button } from "@/components/ui/button";
import { Badge } from "@/components/ui/badge";
import { Input } from "@/components/ui/input";
import { Label } from "@/components/ui/label";
import { RadioGroup, RadioGroupItem } from "@/components/ui/radio-group";
import { Select, SelectContent, SelectItem, SelectTrigger, SelectValue } from "@/components/ui/select";
import { Separator } from "@/components/ui/separator";
import { toast } from "sonner";
import { Minus, Plus, Trash2, ShoppingBag, Coins, CreditCard, ArrowRight, Package } from "lucide-react";
import { DeliveryAddress } from "@/types/database";
import { formatNaira, formatCoins, NIGERIAN_STATES } from "@/lib/constants";
import { cn } from "@/lib/utils";

type CheckoutStep = "cart" | "address" | "payment" | "confirm";

export default function Cart() {
  const { user, wallet } = useAuth();
  const { items, isLoading, updateQuantity, removeFromCart, clearCart, totalNaira, totalCoins } = useCart();
  const navigate = useNavigate();

  const [step, setStep] = useState<CheckoutStep>("cart");
  const [addresses, setAddresses] = useState<DeliveryAddress[]>([]);
  const [selectedAddressId, setSelectedAddressId] = useState<string>("");
  const [paymentMethod, setPaymentMethod] = useState<"coins" | "paystack" | "mixed">("paystack");
  const [coinsToUse, setCoinsToUse] = useState(0);
  const [isProcessing, setIsProcessing] = useState(false);
  const [isNewAddress, setIsNewAddress] = useState(false);
  const [newAddress, setNewAddress] = useState({
    full_name: "",
    phone: "",
    address_line1: "",
    address_line2: "",
    city: "",
    state: "",
  });

  const coinBalance = wallet?.balance || 0;
  const maxCoinsUsable = Math.min(coinBalance, totalCoins);

  // Calculate final amounts
  const coinsValue = paymentMethod === "coins" ? totalCoins : paymentMethod === "mixed" ? coinsToUse : 0;
  const nairaDiscount = Math.floor((coinsValue / totalCoins) * totalNaira);
  const finalNaira = Math.max(0, totalNaira - nairaDiscount);

  useEffect(() => {
    if (user) {
      fetchAddresses();
    }
  }, [user]);

  const fetchAddresses = async () => {
    if (!user) return;
    const { data } = await supabase
      .from("delivery_addresses")
      .select("*")
      .eq("user_id", user.id)
      .order("is_default", { ascending: false });

    if (data) {
      setAddresses(data as DeliveryAddress[]);
      if (data.length > 0) {
        setSelectedAddressId(data[0].id);
      }
    }
  };

  const handleSaveAddress = async () => {
    if (!user) return;

    const { data, error } = await supabase
      .from("delivery_addresses")
      .insert({
        ...newAddress,
        user_id: user.id,
        is_default: addresses.length === 0,
      })
      .select()
      .single();

    if (error) {
      toast.error("Failed to save address");
    } else {
      toast.success("Address saved");
      setAddresses([...addresses, data as DeliveryAddress]);
      setSelectedAddressId(data.id);
      setIsNewAddress(false);
    }
  };

  const handlePlaceOrder = async () => {
    if (!user || items.length === 0) return;

    setIsProcessing(true);

    // Create order
    const { data: orderData, error: orderError } = await supabase
      .from("orders")
      .insert({
        user_id: user.id,
        total_naira: totalNaira,
        total_coins: totalCoins,
        coins_used: paymentMethod === "coins" ? totalCoins : paymentMethod === "mixed" ? coinsToUse : 0,
        naira_paid: finalNaira,
        payment_method: paymentMethod,
        delivery_address_id: selectedAddressId || null,
        order_number: "", // Will be generated by trigger
      })
      .select()
      .single();

    if (orderError) {
      toast.error("Failed to create order");
      setIsProcessing(false);
      return;
    }

    // Create order items
    const orderItems = items.map((item) => ({
      order_id: orderData.id,
      product_id: item.product_id,
      product_name: item.product.name,
      quantity: item.quantity,
      price_naira: item.product.price_naira,
      price_coins: item.product.price_coins,
    }));

    const { error: itemsError } = await supabase.from("order_items").insert(orderItems);

    if (itemsError) {
      toast.error("Failed to add order items");
      setIsProcessing(false);
      return;
    }

    // If payment method requires Paystack (not full coins)
    if (paymentMethod === "paystack" || (paymentMethod === "mixed" && finalNaira > 0)) {
      try {
        const result = await initializePayment({
          type: "order",
          amount: finalNaira,
          email: user.email || "",
          userId: user.id,
          metadata: {
            orderId: orderData.id,
          },
        });

        if (result.success && result.authorization_url) {
          await clearCart();
          window.location.href = result.authorization_url;
          return;
        } else {
          toast.error(result.error || "Failed to initialize payment");
          setIsProcessing(false);
          return;
        }
      } catch (error) {
        toast.error("Payment initialization failed");
        setIsProcessing(false);
        return;
      }
    }

    // If paying with coins only, just clear cart and redirect
    await clearCart();
    toast.success("Order placed successfully!");
    navigate("/dashboard");
    setIsProcessing(false);
  };

  if (!user) {
    return (
      <Layout>
        <div className="container-main py-12">
          <Card className="max-w-md mx-auto">
            <CardContent className="pt-6 text-center">
              <ShoppingBag className="h-12 w-12 mx-auto text-muted-foreground mb-4" />
              <h2 className="text-xl font-bold mb-2">Sign in to view your cart</h2>
              <p className="text-muted-foreground mb-4">
                Create an account to start shopping
              </p>
              <Button onClick={() => navigate("/auth")}>Sign In</Button>
            </CardContent>
          </Card>
        </div>
      </Layout>
    );
  }

  if (isLoading) {
    return (
      <Layout>
        <div className="container-main py-12">
          <div className="flex items-center justify-center min-h-[400px]">
            <div className="animate-spin rounded-full h-12 w-12 border-b-2 border-primary"></div>
          </div>
        </div>
      </Layout>
    );
  }

  if (items.length === 0 && step === "cart") {
    return (
      <Layout>
        <div className="container-main py-12">
          <Card className="max-w-md mx-auto">
            <CardContent className="pt-6 text-center">
              <ShoppingBag className="h-12 w-12 mx-auto text-muted-foreground mb-4" />
              <h2 className="text-xl font-bold mb-2">Your cart is empty</h2>
              <p className="text-muted-foreground mb-4">
                Browse our shop to find the perfect equipment
              </p>
              <Button onClick={() => navigate("/shop")}>Go to Shop</Button>
            </CardContent>
          </Card>
        </div>
      </Layout>
    );
  }

  return (
    <Layout>
      <div className="container-main py-8">
        {/* Progress Steps */}
        <div className="flex items-center justify-center gap-2 mb-8">
          {["cart", "address", "payment", "confirm"].map((s, idx) => (
            <div key={s} className="flex items-center">
              <div
                className={cn(
                  "w-8 h-8 rounded-full flex items-center justify-center text-sm font-medium",
                  step === s || ["cart", "address", "payment", "confirm"].indexOf(step) > idx
                    ? "bg-primary text-primary-foreground"
                    : "bg-muted text-muted-foreground"
                )}
              >
                {idx + 1}
              </div>
              {idx < 3 && (
                <div
                  className={cn(
                    "w-12 h-0.5",
                    ["cart", "address", "payment", "confirm"].indexOf(step) > idx
                      ? "bg-primary"
                      : "bg-muted"
                  )}
                />
              )}
            </div>
          ))}
        </div>

        <div className="grid lg:grid-cols-3 gap-8">
          {/* Main Content */}
          <div className="lg:col-span-2 space-y-6">
            {/* Cart Step */}
            {step === "cart" && (
              <>
                <h1 className="text-2xl font-bold">Shopping Cart</h1>
                <div className="space-y-4">
                  {items.map((item) => (
                    <Card key={item.id}>
                      <CardContent className="p-4">
                        <div className="flex gap-4">
                          <div className="w-20 h-20 rounded-lg bg-muted flex items-center justify-center overflow-hidden">
                            {item.product.image_url ? (
                              <img
                                src={item.product.image_url}
                                alt={item.product.name}
                                className="w-full h-full object-cover"
                              />
                            ) : (
                              <Package className="h-8 w-8 text-muted-foreground" />
                            )}
                          </div>
                          <div className="flex-1">
                            <h3 className="font-semibold">{item.product.name}</h3>
                            <div className="flex gap-3 text-sm text-muted-foreground mt-1">
                              <span>{formatNaira(item.product.price_naira)}</span>
                              <span>•</span>
                              <span className="text-secondary">{formatCoins(item.product.price_coins)} 🪙</span>
                            </div>
                            <div className="flex items-center gap-3 mt-3">
                              <div className="flex items-center border rounded-lg">
                                <Button
                                  variant="ghost"
                                  size="icon"
                                  className="h-8 w-8"
                                  onClick={() => updateQuantity(item.product_id, item.quantity - 1)}
                                >
                                  <Minus className="h-4 w-4" />
                                </Button>
                                <span className="w-8 text-center">{item.quantity}</span>
                                <Button
                                  variant="ghost"
                                  size="icon"
                                  className="h-8 w-8"
                                  onClick={() => updateQuantity(item.product_id, item.quantity + 1)}
                                >
                                  <Plus className="h-4 w-4" />
                                </Button>
                              </div>
                              <Button
                                variant="ghost"
                                size="icon"
                                className="text-destructive"
                                onClick={() => removeFromCart(item.product_id)}
                              >
                                <Trash2 className="h-4 w-4" />
                              </Button>
                            </div>
                          </div>
                          <div className="text-right">
                            <p className="font-semibold">{formatNaira(item.product.price_naira * item.quantity)}</p>
                            <p className="text-sm text-secondary">{formatCoins(item.product.price_coins * item.quantity)} 🪙</p>
                          </div>
                        </div>
                      </CardContent>
                    </Card>
                  ))}
                </div>
              </>
            )}

            {/* Address Step */}
            {step === "address" && (
              <>
                <h1 className="text-2xl font-bold">Delivery Address</h1>
                {addresses.length > 0 && !isNewAddress ? (
                  <div className="space-y-4">
                    <RadioGroup value={selectedAddressId} onValueChange={setSelectedAddressId}>
                      {addresses.map((addr) => (
                        <div key={addr.id} className="flex items-start space-x-3">
                          <RadioGroupItem value={addr.id} id={addr.id} className="mt-1" />
                          <Label htmlFor={addr.id} className="flex-1 cursor-pointer">
                            <Card className={cn(selectedAddressId === addr.id && "border-primary")}>
                              <CardContent className="p-4">
                                <p className="font-medium">{addr.full_name}</p>
                                <p className="text-sm text-muted-foreground">
                                  {addr.address_line1}
                                  {addr.address_line2 && `, ${addr.address_line2}`}
                                </p>
                                <p className="text-sm text-muted-foreground">
                                  {addr.city}, {addr.state}
                                </p>
                                <p className="text-sm text-muted-foreground">{addr.phone}</p>
                              </CardContent>
                            </Card>
                          </Label>
                        </div>
                      ))}
                    </RadioGroup>
                    <Button variant="outline" onClick={() => setIsNewAddress(true)}>
                      Add New Address
                    </Button>
                  </div>
                ) : (
                  <Card>
                    <CardHeader>
                      <CardTitle>Add New Address</CardTitle>
                    </CardHeader>
                    <CardContent className="space-y-4">
                      <div className="grid grid-cols-2 gap-4">
                        <div className="space-y-2">
                          <Label htmlFor="full_name">Full Name</Label>
                          <Input
                            id="full_name"
                            value={newAddress.full_name}
                            onChange={(e) => setNewAddress({ ...newAddress, full_name: e.target.value })}
                          />
                        </div>
                        <div className="space-y-2">
                          <Label htmlFor="phone">Phone Number</Label>
                          <Input
                            id="phone"
                            value={newAddress.phone}
                            onChange={(e) => setNewAddress({ ...newAddress, phone: e.target.value })}
                          />
                        </div>
                      </div>
                      <div className="space-y-2">
                        <Label htmlFor="address_line1">Address Line 1</Label>
                        <Input
                          id="address_line1"
                          value={newAddress.address_line1}
                          onChange={(e) => setNewAddress({ ...newAddress, address_line1: e.target.value })}
                        />
                      </div>
                      <div className="space-y-2">
                        <Label htmlFor="address_line2">Address Line 2 (Optional)</Label>
                        <Input
                          id="address_line2"
                          value={newAddress.address_line2}
                          onChange={(e) => setNewAddress({ ...newAddress, address_line2: e.target.value })}
                        />
                      </div>
                      <div className="grid grid-cols-2 gap-4">
                        <div className="space-y-2">
                          <Label htmlFor="city">City</Label>
                          <Input
                            id="city"
                            value={newAddress.city}
                            onChange={(e) => setNewAddress({ ...newAddress, city: e.target.value })}
                          />
                        </div>
                        <div className="space-y-2">
                          <Label htmlFor="state">State</Label>
                          <Select
                            value={newAddress.state}
                            onValueChange={(value) => setNewAddress({ ...newAddress, state: value })}
                          >
                            <SelectTrigger>
                              <SelectValue placeholder="Select state" />
                            </SelectTrigger>
                            <SelectContent>
                              {NIGERIAN_STATES.map((state) => (
                                <SelectItem key={state} value={state}>
                                  {state}
                                </SelectItem>
                              ))}
                            </SelectContent>
                          </Select>
                        </div>
                      </div>
                      <div className="flex gap-3">
                        {addresses.length > 0 && (
                          <Button variant="outline" onClick={() => setIsNewAddress(false)}>
                            Cancel
                          </Button>
                        )}
                        <Button onClick={handleSaveAddress}>Save Address</Button>
                      </div>
                    </CardContent>
                  </Card>
                )}
              </>
            )}

            {/* Payment Step */}
            {step === "payment" && (
              <>
                <h1 className="text-2xl font-bold">Payment Method</h1>
                <Card>
                  <CardContent className="pt-6 space-y-6">
                    <RadioGroup value={paymentMethod} onValueChange={(v) => setPaymentMethod(v as any)}>
                      {/* Paystack Option */}
                      <div className="flex items-start space-x-3">
                        <RadioGroupItem value="paystack" id="paystack" className="mt-1" />
                        <Label htmlFor="paystack" className="flex-1 cursor-pointer">
                          <div className="flex items-center gap-3">
                            <div className="p-2 rounded-lg bg-primary/10">
                              <CreditCard className="h-5 w-5 text-primary" />
                            </div>
                            <div>
                              <p className="font-medium">Pay with Paystack</p>
                              <p className="text-sm text-muted-foreground">
                                Card, Bank Transfer, USSD
                              </p>
                            </div>
                          </div>
                        </Label>
                      </div>

                      {/* Coins Option */}
                      <div className="flex items-start space-x-3">
                        <RadioGroupItem
                          value="coins"
                          id="coins"
                          className="mt-1"
                          disabled={coinBalance < totalCoins}
                        />
                        <Label
                          htmlFor="coins"
                          className={cn("flex-1 cursor-pointer", coinBalance < totalCoins && "opacity-50")}
                        >
                          <div className="flex items-center gap-3">
                            <div className="p-2 rounded-lg bg-secondary/20">
                              <Coins className="h-5 w-5 text-secondary" />
                            </div>
                            <div>
                              <p className="font-medium">Pay with Coins</p>
                              <p className="text-sm text-muted-foreground">
                                Balance: {formatCoins(coinBalance)} coins
                                {coinBalance < totalCoins && " (Insufficient)"}
                              </p>
                            </div>
                          </div>
                        </Label>
                      </div>

                      {/* Mixed Option */}
                      <div className="flex items-start space-x-3">
                        <RadioGroupItem value="mixed" id="mixed" className="mt-1" disabled={coinBalance === 0} />
                        <Label
                          htmlFor="mixed"
                          className={cn("flex-1 cursor-pointer", coinBalance === 0 && "opacity-50")}
                        >
                          <div className="flex items-center gap-3">
                            <div className="p-2 rounded-lg bg-accent/10">
                              <div className="flex">
                                <Coins className="h-5 w-5 text-accent" />
                                <CreditCard className="h-5 w-5 text-accent -ml-2" />
                              </div>
                            </div>
                            <div>
                              <p className="font-medium">Coins + Paystack</p>
                              <p className="text-sm text-muted-foreground">
                                Use coins for partial payment
                              </p>
                            </div>
                          </div>
                        </Label>
                      </div>
                    </RadioGroup>

                    {paymentMethod === "mixed" && coinBalance > 0 && (
                      <div className="space-y-3 pt-4 border-t">
                        <Label>Coins to use: {formatCoins(coinsToUse)}</Label>
                        <Input
                          type="range"
                          min={0}
                          max={maxCoinsUsable}
                          value={coinsToUse}
                          onChange={(e) => setCoinsToUse(parseInt(e.target.value))}
                          className="w-full"
                        />
                        <div className="flex justify-between text-sm text-muted-foreground">
                          <span>0</span>
                          <span>{formatCoins(maxCoinsUsable)}</span>
                        </div>
                      </div>
                    )}
                  </CardContent>
                </Card>
              </>
            )}

            {/* Confirm Step */}
            {step === "confirm" && (
              <>
                <h1 className="text-2xl font-bold">Review Order</h1>
                <div className="space-y-4">
                  {/* Items Summary */}
                  <Card>
                    <CardHeader>
                      <CardTitle className="text-lg">Items ({items.length})</CardTitle>
                    </CardHeader>
                    <CardContent className="space-y-3">
                      {items.map((item) => (
                        <div key={item.id} className="flex justify-between text-sm">
                          <span>
                            {item.product.name} × {item.quantity}
                          </span>
                          <span>{formatNaira(item.product.price_naira * item.quantity)}</span>
                        </div>
                      ))}
                    </CardContent>
                  </Card>

                  {/* Address Summary */}
                  <Card>
                    <CardHeader>
                      <CardTitle className="text-lg">Delivery Address</CardTitle>
                    </CardHeader>
                    <CardContent>
                      {addresses.find((a) => a.id === selectedAddressId) && (
                        <div className="text-sm">
                          <p className="font-medium">
                            {addresses.find((a) => a.id === selectedAddressId)?.full_name}
                          </p>
                          <p className="text-muted-foreground">
                            {addresses.find((a) => a.id === selectedAddressId)?.address_line1}
                          </p>
                          <p className="text-muted-foreground">
                            {addresses.find((a) => a.id === selectedAddressId)?.city},{" "}
                            {addresses.find((a) => a.id === selectedAddressId)?.state}
                          </p>
                        </div>
                      )}
                    </CardContent>
                  </Card>

                  {/* Payment Summary */}
                  <Card>
                    <CardHeader>
                      <CardTitle className="text-lg">Payment Method</CardTitle>
                    </CardHeader>
                    <CardContent>
                      <div className="flex items-center gap-2">
                        {paymentMethod === "coins" && <Coins className="h-5 w-5 text-secondary" />}
                        {paymentMethod === "paystack" && <CreditCard className="h-5 w-5 text-primary" />}
                        {paymentMethod === "mixed" && (
                          <>
                            <Coins className="h-5 w-5 text-secondary" />
                            <span>+</span>
                            <CreditCard className="h-5 w-5 text-primary" />
                          </>
                        )}
                        <span className="capitalize">{paymentMethod}</span>
                      </div>
                    </CardContent>
                  </Card>
                </div>
              </>
            )}
          </div>

          {/* Order Summary Sidebar */}
          <div>
            <Card className="sticky top-24">
              <CardHeader>
                <CardTitle>Order Summary</CardTitle>
              </CardHeader>
              <CardContent className="space-y-4">
                <div className="space-y-2">
                  <div className="flex justify-between text-sm">
                    <span className="text-muted-foreground">Subtotal</span>
                    <span>{formatNaira(totalNaira)}</span>
                  </div>
                  {(paymentMethod === "coins" || (paymentMethod === "mixed" && coinsToUse > 0)) && (
                    <div className="flex justify-between text-sm text-secondary">
                      <span>Coins Discount</span>
                      <span>-{formatNaira(nairaDiscount)}</span>
                    </div>
                  )}
                  <div className="flex justify-between text-sm">
                    <span className="text-muted-foreground">Delivery</span>
                    <span>Free</span>
                  </div>
                </div>
                <Separator />
                <div className="flex justify-between font-semibold">
                  <span>Total</span>
                  <div className="text-right">
                    <p>{formatNaira(finalNaira)}</p>
                    {coinsValue > 0 && (
                      <p className="text-sm font-normal text-secondary">
                        + {formatCoins(coinsValue)} coins
                      </p>
                    )}
                  </div>
                </div>

                {/* Coin Benefits (only show on cart step) */}
                {step === "cart" && paymentMethod === "paystack" && (
                  <CoinBenefitsBanner variant="compact" />
                )}

                {/* Action Buttons */}
                <div className="space-y-2 pt-4">
                  {step === "cart" && (
                    <Button className="w-full" onClick={() => setStep("address")}>
                      Proceed to Checkout
                      <ArrowRight className="h-4 w-4 ml-2" />
                    </Button>
                  )}
                  {step === "address" && (
                    <>
                      <Button
                        className="w-full"
                        onClick={() => setStep("payment")}
                        disabled={!selectedAddressId}
                      >
                        Continue to Payment
                        <ArrowRight className="h-4 w-4 ml-2" />
                      </Button>
                      <Button variant="outline" className="w-full" onClick={() => setStep("cart")}>
                        Back to Cart
                      </Button>
                    </>
                  )}
                  {step === "payment" && (
                    <>
                      <Button className="w-full" onClick={() => setStep("confirm")}>
                        Review Order
                        <ArrowRight className="h-4 w-4 ml-2" />
                      </Button>
                      <Button variant="outline" className="w-full" onClick={() => setStep("address")}>
                        Back
                      </Button>
                    </>
                  )}
                  {step === "confirm" && (
                    <>
                      <Button
                        className="w-full gradient-primary"
                        onClick={handlePlaceOrder}
                        disabled={isProcessing}
                      >
                        {isProcessing ? "Processing..." : "Place Order"}
                      </Button>
                      <Button variant="outline" className="w-full" onClick={() => setStep("payment")}>
                        Back
                      </Button>
                    </>
                  )}
                </div>
              </CardContent>
            </Card>
          </div>
        </div>
      </div>
    </Layout>
  );
}
